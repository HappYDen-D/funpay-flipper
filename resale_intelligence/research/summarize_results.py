"""Render existing scenario JSON as Markdown; does not run simulations or use network."""
import json
from pathlib import Path


def main():
    folder = Path(__file__).resolve().parent
    data = json.loads((folder / 'scenario_results.json').read_text(encoding='utf-8'))
    names = {
        'legacy_prices_with_constraints': 'Старые цены с ограничениями',
        'compressed_global48': 'Умеренный, ограничение аккаунта 48 ч',
        'compressed_per_credit48': 'Умеренный, холд отдельных поступлений',
        'compressed_no_hold': 'Умеренный, без холда',
        'compressed_cost_5rub_day': 'Умеренный, расходы 5 ₽/сутки',
        'stress': 'Стресс',
    }
    def money(value):
        return f'{value:,.2f}'.replace(',', ' ').replace('.', ',') + ' ₽'
    lines = [
        '# Сводка сценарных расчётов', '',
        'Начальный капитал — 350 ₽; горизонт — 30 суток; 300 прогонов каждого сценария, seed 0–299.', '',
        '**Все параметры синтетические. Это анализ чувствительности, а не прогноз рынка.**', '',
        '| Сценарий | Капитал P10 | Капитал P50 | Капитал P90 | Прибыль P50 | Доступно P50 | Убыточных прогонов |',
        '|---|---:|---:|---:|---:|---:|---:|',
    ]
    for row in data['results']:
        values = [names[row['scenario']], *(money(row['equity'][q]) for q in ('p10','p50','p90')),
                  money(row['profit']['p50']), money(row['available_cash']['p50']),
                  f"{round(row['loss_probability']*row['runs'])} из {row['runs']}"]
        lines.append('| ' + ' | '.join(values) + ' |')
    lines.extend([
        '', 'P10/P50/P90 — квантили исходов модели, не доверительные границы фактического дохода.', '',
        'Ни в одном из этих прогонов цель 25 000 ₽ не достигнута по капиталу, прибыли или доступным деньгам. '
        'Это результат именно выбранных ограничений спроса и запаса, а не доказательство невозможности цели.', '',
        'Ноль доступных средств при положительном капитале может означать временный запрет закупки с баланса. '
        'Отрицательные активы стресс-сценария отражают накопленные операционные обязательства; покупки в долг не выполняются.', '',
        'Сопоставление режимов холда не является строгим экспериментом с одинаковыми траекториями спроса: '
        'из-за разного числа событий последовательности генератора расходятся. Результаты описывают распределения сценариев.', '',
        'Постоянный спрос, максимум четыре незавершённых позиции на категорию и шесть условных поставщиков '
        'описывают небольшой пилот. Их масштабирование нужно обосновать наблюдениями.', '',
        '[Полный отчёт и источники](RESEARCH_REPORT.md) · '
        '[Параметры и дневные снимки](scenario_results.json) · '
        '[Симулятор](../models/compounding_simulation.py)', '',
    ])
    (folder / 'SCENARIO_SUMMARY.md').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
